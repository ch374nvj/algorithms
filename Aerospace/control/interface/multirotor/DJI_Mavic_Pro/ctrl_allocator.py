import numpy as np

class LocalAllocator:
    """
        Local (around a trim/any specific condition) linear control allocator  for
        DJI Mavic Pro quadcopter model.
        Config: X
        Motor ordering:
        1. Front-right
        2. Rear-right
        3. Rear-left
        4. Front-left
    """

    def __init__(self, lateral_length, kq) -> None:
        self.a = lateral_length/np.sqrt(2) # Lateral length from center to motor
        self.kq = kq # Torque drag coefficient, estimated for local condition

    def allocate(self, trim_thrust, control):
        """
            Apply allocator on incoming control commands and output thrust commands
        Args:
            trim_thrust (array): Thrust val generated by all motors at trim
            control (array): [delta_T_cmd L_cmd M_cmd N_cmd]
        """
        # Control Allocation from thrust and moment commands
        # delta_T = A_alloc * delta_u
        # Where 
        # A_alloc:
        #           [1      -1/a       +1/a       -1/kq]
        #           [1      -1/a       -1/a       +1/kq]
        #   1/4 *   [1      +1/a       -1/a       -1/kq]
        #           [1      +1/a       +1/a       +1/kq]
        # 
        # delta_u:
        #           [delta_T_cmd    L_cmd   M_cmd   N_cmd]'
        # delta_T:
        #           [delta_T1    delta_T2     delta_T3     delta_T4]'
        # delta_Ti corresponds to thrust perturbs at motor i from trim thrust/rpm
        # i.e., T_trim + delta_T -> T_cmd -> RPM cmd
        # 
        # The above matrix mul calc will be split into 4 equation, so the code can be directly
        # used for embedded application.
        # 

        [delta_T_cmd, L_cmd, M_cmd, N_cmd] = control
        
        delta_T1 = delta_T_cmd/4 - L_cmd/(4*self.a) + M_cmd/(4*self.a) - N_cmd/(4*self.kq)
        delta_T2 = delta_T_cmd/4 - L_cmd/(4*self.a) - M_cmd/(4*self.a) + N_cmd/(4*self.kq)
        delta_T3 = delta_T_cmd/4 + L_cmd/(4*self.a) - M_cmd/(4*self.a) - N_cmd/(4*self.kq)
        delta_T4 = delta_T_cmd/4 + L_cmd/(4*self.a) + M_cmd/(4*self.a) + N_cmd/(4*self.kq)

        T_cmd = np.array([delta_T1, delta_T2, delta_T3, delta_T4])

        return trim_thrust + T_cmd

